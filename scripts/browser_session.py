def _height(fmt: dict) -> int:
    try:
        return int(fmt.get("height") or 0)
    except (TypeError, ValueError):
        return 0


def _bitrate(fmt: dict) -> float:
    try:
        return float(fmt.get("bitrate") or 0)
    except (TypeError, ValueError):
        return 0.0


def summarize_player(player: dict | None, max_height: int = 1080) -> dict:
    """Turn ytInitialPlayerResponse into the compact facts the recorder needs."""
    facts: dict = {
        "video_id": "",
        "playability": "",
        "playability_reason": "",
        "title": "",
        "author": "",
        "is_live": False,
        "live_status": "",
        "hls_manifest_url": "",
        "dash_manifest_url": "",
        "video_url": "",
        "audio_url": "",
        "muxed_url": "",
        "muxed_quality": "",
        "video_itag": "",
        "audio_itag": "",
        "video_quality": "",
        "formats_count": 0,
    }
    if not isinstance(player, dict):
        return facts

    status = player.get("playabilityStatus") or {}
    facts["playability"] = status.get("status") or ""
    facts["playability_reason"] = status.get("reason") or ""

    details = player.get("videoDetails") or {}
    facts["video_id"] = details.get("videoId") or ""
    facts["title"] = details.get("title") or ""
    facts["author"] = details.get("author") or ""
    facts["is_live"] = bool(details.get("isLive")) or (
        details.get("isLiveContent") is True and facts["playability"] == "OK"
    )

    micro = player.get("microformat") or {}
    player_micro = micro.get("playerMicroformatRenderer") or {}
    if player_micro.get("liveBroadcastDetails"):
        lbd = player_micro["liveBroadcastDetails"]
        facts["live_status"] = "is_live" if lbd.get("isLiveNow") else "was_live"
        if lbd.get("isLiveNow"):
            facts["is_live"] = True

    streaming = player.get("streamingData") or {}
    facts["hls_manifest_url"] = streaming.get("hlsManifestUrl") or ""
    facts["dash_manifest_url"] = streaming.get("dashManifestUrl") or ""

    formats = list(streaming.get("adaptiveFormats") or [])
    # Live players expose the muxed formats here; VOD exposes them in "formats".
    formats += list(streaming.get("formats") or [])
    facts["formats_count"] = len(formats)

    videos = []
    audios = []
    muxed = []
    for fmt in formats:
        if not isinstance(fmt, dict):
            continue
        url = fmt.get("url") or ""
        if not url:
            continue  # ciphered URL: only the manifest path can play it
        mime = (fmt.get("mimeType") or "").lower()
        audio_quality = str(fmt.get("audioQuality") or "").upper()
        has_audio = "audio" in mime or (audio_quality and audio_quality != "AUDIO_QUALITY_NONE")
        if "video" in mime and has_audio:
            if _height(fmt) and _height(fmt) <= max_height:
                muxed.append(fmt)
        elif "video" in mime:
            if _height(fmt) and _height(fmt) <= max_height:
                videos.append(fmt)
        elif has_audio:
            audios.append(fmt)

    if videos:
        best = max(videos, key=lambda f: (_height(f), _bitrate(f)))
        facts["video_url"] = best.get("url") or ""
        facts["video_itag"] = str(best.get("itag") or "")
        facts["video_quality"] = str(best.get("qualityLabel") or best.get("quality") or "")
    if muxed:
        best_m = max(muxed, key=lambda f: (_height(f), _bitrate(f)))
        facts["muxed_url"] = best_m.get("url") or ""
        facts["muxed_quality"] = str(best_m.get("qualityLabel") or best_m.get("quality") or "")
    if audios:
        best_a = max(audios, key=lambda f: (_bitrate(f), str(f.get("mimeType", ""))))
        facts["audio_url"] = best_a.get("url") or ""
        facts["audio_itag"] = str(best_a.get("itag") or "")

    return facts


PLAYER_RE_STRICT = re.compile(
    r"ytInitialPlayerResponse\s*=\s*(\{.+?\})\s*;\s*(?:var\s|const\s|let\s|</script>)",
    re.S,
)
PLAYER_RE_LOOSE = re.compile(r"ytInitialPlayerResponse\s*=\s*(\{.+?\});", re.S)


def parse_player_from_html(html: str) -> dict | None:
    """Best-effort pull of ytInitialPlayerResponse out of a watch page."""
    if not html:
        return None
    for pattern in (PLAYER_RE_STRICT, PLAYER_RE_LOOSE):
        m = pattern.search(html)
        if not m:
            continue
        try:
            return json.loads(m.group(1))
        except json.JSONDecodeError:
            continue
    return None


def is_blocked_text(text: str) -> bool:
    low = (text or "").lower()
    return any(marker in low for marker in BOT_MARKERS)


def needs_consent(text: str) -> bool:
    low = (text or "").lower()
    return any(marker in low for marker in CONSENT_MARKERS)


