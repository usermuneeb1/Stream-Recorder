# ═══════════════════════════════════════════════════════════════════════════════
#  COOKIE CONVERSION (pure, unit-testable, no browser needed)
# ═══════════════════════════════════════════════════════════════════════════════

def _clean(value) -> str:
    """Cookie values must be single-line and tab-free for Netscape format."""
    text = "" if value is None else str(value)
    return text.replace("\t", " ").replace("\r", "").replace("\n", "")


def to_netscape(cookies, now: float | None = None) -> str:
    """Convert a Selenium/CDP cookie list into a Netscape cookies.txt body.

    Selenium returns dicts like:
        {"name": "SOCS", "value": "CAI", "domain": ".youtube.com",
         "path": "/", "secure": True, "httpOnly": False,
         "expiry": 1790000000, "sameSite": "Lax"}

    Netscape columns (tab separated):
        domain  include_subdomains  path  secure  expiry  name  value

    httpOnly cookies are prefixed with "#HttpOnly_" (the convention curl and
    yt-dlp both understand). Session cookies (no expiry) get a one-year expiry
    because some yt-dlp paths ignore "expiry=0" cookies mid-download.
    """
    now = time.time() if now is None else now
    default_expiry = int(now) + 365 * 24 * 3600
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by scripts/browser_session.py (SeleniumBase UC session).",
        "# https://curl.se/docs/http-cookies.html",
        "",
    ]
    seen = set()
    for c in cookies or []:
        if not isinstance(c, dict):
            continue
        name = _clean(c.get("name"))
        if not name:
            continue
        domain = _clean(c.get("domain")) or ".youtube.com"
        if not domain.startswith("."):
            # A host-only cookie is still valid, but adding the leading dot
            # makes it survive www./m./music. subdomain hops inside YouTube.
            if domain and "." in domain and not domain.replace(".", "").isdigit():
                domain = "." + domain.lstrip(".")
        path = _clean(c.get("path")) or "/"

        secure = bool(c.get("secure"))
        if name.startswith(("__Secure-", "__Host-")):
            secure = True

        expiry = c.get("expiry", c.get("expires"))
        try:
            expiry = int(float(expiry))
        except (TypeError, ValueError):
            expiry = 0
        if expiry <= 0:
            expiry = default_expiry

        key = (domain, path, name)
        if key in seen:
            continue
        seen.add(key)

        prefix = "#HttpOnly_" if c.get("httpOnly") else ""
        lines.append(
            "\t".join(
                [
                    f"{prefix}{domain}",
                    "TRUE" if domain.startswith(".") else "FALSE",
                    path,
                    "TRUE" if secure else "FALSE",
                    str(expiry),
                    name,
                    _clean(c.get("value")),
                ]
            )
        )
    return "\n".join(lines) + "\n"


def to_env(facts: dict) -> str:
    """Render a shell-sourceable KEY='value' file."""
    out = ["# Generated by scripts/browser_session.py"]
    for key, value in facts.items():
        if value is None:
            continue
        out.append(f"{key}={shlex.quote(str(value))}")
    return "\n".join(out) + "\n"


