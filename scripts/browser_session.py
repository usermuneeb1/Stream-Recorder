def selftest() -> int:
    failures = []

    def check(name, cond, detail=""):
        if cond:
            log(f"  PASS: {name}")
        else:
            failures.append(name)
            log(f"  FAIL: {name} {detail}")

    sample = [
        {"name": "VISITOR_INFO1_LIVE", "value": "abc123", "domain": ".youtube.com",
         "path": "/", "secure": True, "httpOnly": True, "expiry": 1900000000},
        {"name": "SOCS", "value": "CAI", "domain": "youtube.com", "path": "/"},
        {"name": "bad\tname", "value": "line\nbreak", "domain": ".youtube.com"},
    ]
    body = to_netscape(sample, now=1700000000)
    # Cookie rows are the only lines with exactly 6 tabs ("#HttpOnly_" rows
    # legitimately start with '#' so a prefix filter would drop them).
    rows = [ln for ln in body.splitlines() if ln.count("\t") == 6]
    check("netscape: header present", body.startswith("# Netscape HTTP Cookie File"))
    check("netscape: three rows written", len(rows) == 3, f"got {len(rows)}")
    check("netscape: httpOnly prefixed", any(r.startswith("#HttpOnly_.youtube.com") for r in body.splitlines()))
    check("netscape: tab separated", all(len(r.split("\t")) == 7 for r in rows))
    check("netscape: session cookie gets expiry",
          rows[1].split("\t")[4].isdigit() and int(rows[1].split("\t")[4]) > 1700000000)
    check("netscape: no raw newlines", "\nbreak" not in body)
    check("netscape: host-only domain dotted",
          rows[1].split("\t")[0] == ".youtube.com")

    player = {
        "playabilityStatus": {"status": "OK"},
        "videoDetails": {"videoId": "VID12345678", "title": "T", "author": "A", "isLive": True},
        "streamingData": {
            "hlsManifestUrl": "https://manifest.googlevideo.com/x.m3u8",
            "adaptiveFormats": [
                {"itag": 137, "mimeType": "video/mp4", "height": 1080,
                 "bitrate": "4000000", "url": "https://v/1080", "qualityLabel": "1080p"},
                {"itag": 136, "mimeType": "video/mp4", "height": 720,
                 "bitrate": "2000000", "url": "https://v/720", "qualityLabel": "720p"},
                {"itag": 140, "mimeType": "audio/mp4", "bitrate": "128000",
                 "url": "https://a/140", "audioQuality": "AUDIO_QUALITY_MEDIUM"},
                {"itag": 251, "mimeType": "audio/webm", "bitrate": "160000",
                 "url": "https://a/251", "audioQuality": "AUDIO_QUALITY_HIGH"},
            ],
        },
    }
    facts = summarize_player(player)
    check("player: live detected", facts["is_live"] is True)
    check("player: video id surfaced", facts["video_id"] == "VID12345678")
    check("player: hls captured", facts["hls_manifest_url"].endswith(".m3u8"))
    check("player: best video <=1080", facts["video_url"] == "https://v/1080")
    check("player: best audio", facts["audio_url"] == "https://a/251")
    check("player: counts formats", facts["formats_count"] == 4)

    capped = summarize_player(player, max_height=720)
    check("player: max_height honoured", capped["video_url"] == "https://v/720")

    censored = summarize_player({"playabilityStatus": {"status": "LOGIN_REQUIRED",
                                                       "reason": "Sign in to confirm you're not a bot"}})
    check("player: blocked status surfaced",
          censored["playability"] == "LOGIN_REQUIRED" and "bot" in censored["playability_reason"])

    html = ('<html><script>var ytInitialPlayerResponse = {"playabilityStatus":'
            '{"status":"OK"}};</script></html>')
    check("html: player response parsed", (parse_player_from_html(html) or {}).get("playabilityStatus", {}).get("status") == "OK")
    check("html: garbage tolerated", parse_player_from_html("nope") is None)

    env = to_env({"A": "has space", "B": "x'y"})
    check("env: quoting", "A='has space'" in env and "B='x'\"'\"'y'" in env)

    check("blocked text", is_blocked_text("Sign in to confirm you're not a bot"))
    check("consent text", needs_consent("Before you continue to YouTube"))
    check("clean text", not is_blocked_text("Live now"))

    print()
    if failures:
        print(f"== browser_session selftest: {len(failures)} failed ==")
        return 1
    print("== browser_session selftest: all passed ==")
    return 0


