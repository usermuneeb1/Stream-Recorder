# ── Bot / consent page markers ────────────────────────────────────────────────
BOT_MARKERS = (
    "confirm you're not a bot",
    "confirm you are not a bot",
    "sign in to confirm",
    "unusual traffic",
    "this request looks automated",
)
CONSENT_MARKERS = (
    "before you continue to youtube",
    "we value your privacy",
    "accept all",
)

