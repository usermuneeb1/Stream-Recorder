def _uc_method(sb, name):
    """UC helpers live on sb in some versions and on sb.driver in others."""
    fn = getattr(sb, name, None)
    if callable(fn):
        return fn
    driver = getattr(sb, "driver", None)
    fn = getattr(driver, name, None) if driver is not None else None
    return fn if callable(fn) else None


def _body_text(sb) -> str:
    try:
        return sb.get_text("body") or ""
    except Exception:
        try:
            return sb.get_page_source() or ""
        except Exception:
            return ""


def _accept_consent(sb) -> bool:
    """Click YouTube's cookie-consent banner if it is in the way."""
    script = """
    const wanted = /accept all|i agree|agree to all|reject all/i;
    const nodes = [...document.querySelectorAll('button, tp-yt-paper-button, a')];
    const hit = nodes.find(n => wanted.test((n.innerText || n.getAttribute('aria-label') || '').trim()));
    if (hit) { hit.click(); return (hit.innerText || hit.getAttribute('aria-label') || '').trim(); }
    return '';
    """
    try:
        clicked = sb.execute_script(script)
    except Exception:
        return False
    if clicked:
        log(f"  consent banner clicked: {clicked!r}")
        time.sleep(2)
        return True
    return False


def _clear_bot_wall(sb, url: str, attempts: int = 2) -> bool:
    """Try the UC-mode CAPTCHA/GUI handlers, then reload. True = cleared."""
    click = _uc_method(sb, "uc_gui_click_captcha")
    handle = _uc_method(sb, "uc_gui_handle_captcha")
    opener = _uc_method(sb, "uc_open_with_reconnect")

    for attempt in range(1, attempts + 1):
        log(f"  bot wall detected, clearing attempt {attempt}/{attempts}")
        for fn in (click, handle):
            if not fn:
                continue
            try:
                fn()
                time.sleep(3)
            except Exception as exc:  # pyautogui/display problems must not abort
                log(f"  (GUI handler unavailable: {type(exc).__name__}: {exc})")
        if opener:
            try:
                opener(url, 4)
            except Exception:
                pass
        time.sleep(4)
        text = _body_text(sb)
        if not is_blocked_text(text):
            log("  bot wall cleared")
            return True
    return False


def capture_session(url: str, outdir: str, headed: bool = False,
                    max_wait: int = 60, max_height: int = 1080,
                    profile_dir: str = "") -> int:
    """Open the page in UC-mode Chrome, then write cookies/stream.json/env."""
    try:
        from seleniumbase import SB
    except Exception as exc:  # pragma: no cover - depends on install
        log(f"SeleniumBase unavailable: {type(exc).__name__}: {exc}")
        return 3

    os.makedirs(outdir, exist_ok=True)
    cookies_path = os.path.join(outdir, "cookies.txt")
    stream_path = os.path.join(outdir, "stream.json")
    env_path = os.path.join(outdir, "browser.env")

    # A HEADED browser under Xvfb is the most convincing fingerprint (real GPU,
    # real window, real input pipeline). Headless is only used when Xvfb is not
    # installed, because YouTube weights headless Chrome far more heavily.
    is_linux = sys.platform.startswith("linux")
    has_display = bool(os.environ.get("DISPLAY"))
    has_xvfb = shutil.which("Xvfb") is not None

    sb_kwargs = dict(
        uc=True,                 # undetected-chromedriver (the actual bypass)
        locale_code="en",
        ad_block_on=False,       # ad blocking rewrites the DOM; keep it off
        window_size="1366,768",
    )
    if headed and (has_display or has_xvfb):
        sb_kwargs.update(headless=False, xvfb=not has_display and is_linux)
    elif is_linux and has_xvfb:
        sb_kwargs.update(headless=False, xvfb=True)
    else:
        sb_kwargs.update(headless=True, xvfb=False)
    if profile_dir:
        sb_kwargs["user_data_dir"] = profile_dir

    facts: dict = {}
    cookies: list = []
    blocked = False
    player: dict | None = None
    ua = ""

    try:
        with SB(**sb_kwargs) as sb:
            opener = _uc_method(sb, "uc_open_with_reconnect")
            if opener:
                opener(url, 6)
            else:  # older/newer API drift: plain open still uses the UC driver
                sb.open(url)
            time.sleep(2)

            text = _body_text(sb)
            if needs_consent(text):
                _accept_consent(sb)
            if is_blocked_text(text):
                if not _clear_bot_wall(sb, url):
                    blocked = True

            # Give the player a moment to hydrate before reading ytInitial...
            deadline = time.time() + max_wait
            while time.time() < deadline:
                try:
                    raw = sb.execute_script(
                        "return window.ytInitialPlayerResponse"
                        " ? JSON.stringify(window.ytInitialPlayerResponse) : null"
                    )
                except Exception:
                    raw = None
                player = json.loads(raw) if raw else parse_player_from_html(
                    sb.get_page_source()
                )
                if player and (player.get("streamingData") or player.get("playabilityStatus")):
                    break
                if is_blocked_text(_body_text(sb)):
                    blocked = True
                    break
                time.sleep(3)

            try:
                cookies = sb.get_cookies() or []
            except Exception as exc:
                log(f"  cookie read failed: {type(exc).__name__}: {exc}")
                cookies = []

            try:
                ua = sb.execute_script("return navigator.userAgent") or ""
            except Exception:
                ua = ""
            try:
                visitor = sb.execute_script(
                    "try { return ytcfg.get('VISITOR_DATA'); } catch(e) { return ''; }"
                ) or ""
            except Exception:
                visitor = ""
    except Exception as exc:
        log(f"browser session error: {type(exc).__name__}: {exc}")
        if not cookies:
            return 4
        visitor = ""

    player_facts = summarize_player(player, max_height=max_height)

    # A "blocked" page still yields cookies worth trying; only claim success
    # when we actually got a jar to hand to yt-dlp.
    with open(cookies_path, "w", encoding="utf-8") as fh:
        fh.write(to_netscape(cookies))

    stream = {
        "ok": bool(cookies) and not blocked,
        "blocked": blocked,
        "mode": "uc",
        "cookie_export": True,
        "video_id": "",
        "url": url,
        "user_agent": ua,
        "visitor_data": visitor,
        "cookies_file": cookies_path,
        "cookie_count": len(cookies),
        "captured_at": int(time.time()),
        **player_facts,
    }
    # Prefer the id the player reported: a /live URL redirects, so the URL
    # string alone tells us nothing about which broadcast we landed on.
    if not stream.get("video_id"):
        m = re.search(r"(?:v=|youtu\.be/|/live/)([A-Za-z0-9_-]{11})", url)
        if m:
            stream["video_id"] = m.group(1)
    stream["video_id"] = stream["video_id"] or player_facts.get("video_id") or ""

    with open(stream_path, "w", encoding="utf-8") as fh:
        json.dump(stream, fh, indent=2)

    env_facts = {
        "BROWSER_MODE": "uc",
        "BROWSER_SESSION_OK": "1" if stream["ok"] else "0",
        "BROWSER_SESSION_BLOCKED": "1" if blocked else "0",
        "BROWSER_COOKIES_FILE": cookies_path,
        "BROWSER_STREAM_JSON": stream_path,
        "BROWSER_UA": ua,
        "BROWSER_VISITOR_DATA": visitor,
        "BROWSER_IS_LIVE": "1" if player_facts["is_live"] else "0",
        "BROWSER_PLAYABILITY": player_facts["playability"],
        "BROWSER_COOKIE_COUNT": len(cookies),
        "BROWSER_HLS_MANIFEST": player_facts["hls_manifest_url"],
        "BROWSER_DASH_MANIFEST": player_facts["dash_manifest_url"],
    }
    with open(env_path, "w", encoding="utf-8") as fh:
        fh.write(to_env(env_facts))

    log(f"  cookies: {len(cookies)} -> {cookies_path}")
    log(f"  playability: {player_facts['playability'] or 'unknown'}"
        f"  live: {player_facts['is_live']}")
    if player_facts["hls_manifest_url"]:
        log("  hls manifest: captured")
    if player_facts["dash_manifest_url"]:
        log("  dash manifest: captured")

    # Deliberately NOT "return 2 when blocked": a wall page still sets
    # VISITOR_INFO1_LIVE / __Secure-*PSID / SOCS, and that jar is frequently
    # enough for yt-dlp to get through on the next hop. The caller decides how
    # much to trust it (it logs the blocked flag and keeps the jar).
    if not cookies:
        return 2
    return 0


