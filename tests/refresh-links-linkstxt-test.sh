#!/usr/bin/env bash
# ╔══════════════════════════════════════════════════════════════════════════════╗
# ║  Regression test: refresh-links.sh must mark [EXPIRED] links IN links.txt,   ║
# ║  not overwrite links.txt with a mutated copy of data/recordings.json.        ║
# ║                                                                              ║
# ║  Symptom (main, 2026-07-12 → 2026-10-11): every "Link refresh: N expired     ║
# ║  links marked" commit replaced links.txt (legacy text feed, "entries are     ║
# ║  never deleted") with recordings.json JSON carrying " [EXPIRED]" inside URL  ║
# ║  strings, wiping every text block update-links.sh had prepended since the    ║
# ║  previous refresh. git log confirms the alternation: text-blocks=1..2 after  ║
# ║  a recording, 0 after the next refresh — 14 commits in a row.                ║
# ║                                                                              ║
# ║  Root cause: refresh_links() reads recordings.json into a variable named     ║
# ║  links_content, applies mark_dead_in_links_txt() to THAT, and writes the     ║
# ║  result to links.txt.                                                        ║
# ║                                                                              ║
# ║  This harness stubs curl (GitHub contents API for both files, gofile API     ║
# ║  with one dead code, PUT capture) and asserts on the bytes written.          ║
# ╚══════════════════════════════════════════════════════════════════════════════╝
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"
TARGET="$ROOT/scripts/refresh-links.sh"

FAILURES=0
ok()  { echo "  ✅ $1"; }
bad() { echo "  ❌ $1"; FAILURES=$((FAILURES+1)); }

WORKDIR="$(mktemp -d)"
trap 'rm -rf "$WORKDIR"' EXIT
STUBBIN="$WORKDIR/bin"; mkdir -p "$STUBBIN" "$WORKDIR/puts"

DEAD_URL="https://gofile.io/d/DeadA1"
LIVE_URL="https://gofile.io/d/LiveB2"

RECS_B64=$(python3 - <<'PY'
import base64, json
recs = [
  {"video_id":"vidA","title":"Fixture A","gofile_link":"https://gofile.io/d/DeadA1","pixeldrain_link":"https://pixeldrain.com/u/FixA1","archive_link":"https://archive.org/details/fixA"},
  {"video_id":"vidB","title":"Fixture B","gofile_link":"https://gofile.io/d/LiveB2","pixeldrain_link":"https://pixeldrain.com/u/FixB2","archive_link":"https://archive.org/details/fixB"},
]
print(base64.b64encode(json.dumps(recs).encode()).decode())
PY
)

# Legacy links.txt: header + 2 blocks that exist in recordings.json + 1 old block
# ("Old C") that only exists here — the feed keeps entries forever.
make_links_txt() {  # $1 = marker to put after the dead URL ("" or " [EXPIRED]")
cat <<EOF
# Stream Recorder links archive
# Generated by Automated Stream Recorder v2.0.0
# Newest entries at the top. Entries are never deleted.

========================================
Date:     2026-10-10 03:37:08 AM PKT
Title:    Fixture A
URL:      https://www.youtube.com/watch?v=vidA
--- Links ---
[gofile:HD] ${DEAD_URL}$1
[pixeldrain:HD] https://pixeldrain.com/u/FixA1
[archive:HD] https://archive.org/details/fixA (PERMANENT)
========================================
Date:     2026-10-04 03:37:08 AM PKT
Title:    Fixture B
URL:      https://www.youtube.com/watch?v=vidB
--- Links ---
[gofile:HD] ${LIVE_URL}
[pixeldrain:HD] https://pixeldrain.com/u/FixB2
[archive:HD] https://archive.org/details/fixB (PERMANENT)
========================================
Date:     2026-03-01 03:37:08 AM PKT
Title:    Old C (not in recordings.json any more)
URL:      https://www.youtube.com/watch?v=vidC
--- Links ---
[gofile:HD] https://gofile.io/d/OldC3
[archive:HD] https://archive.org/details/fixC (PERMANENT)
========================================
EOF
}

# The curl stub reads the links.txt fixture from a file so cases can swap it.
LINKS_FIXTURE="$WORKDIR/links.fixture"

cat > "$STUBBIN/curl" <<STUB
#!/usr/bin/env bash
# Minimal curl double. Understands: -o FILE, -w FMT, -d @FILE, -X PUT, URL.
out=""; data=""; method="GET"; url=""; wfmt=""
while (( \$# )); do
  case "\$1" in
    -o) out="\$2"; shift 2;;
    -w) wfmt="\$2"; shift 2;;
    -d|--data|--data-binary) data="\$2"; shift 2;;
    -X) method="\$2"; shift 2;;
    -H|--max-time|-F|-A|--user-agent|--retry|--retry-delay|--connect-timeout) shift 2;;
    http*|https*) url="\$1"; shift;;
    *) shift;;
  esac
done
emit() {  # \$1 = http code, \$2 = body
  if [[ -n "\$out" ]]; then printf '%s' "\$2" > "\$out"; else printf '%s' "\$2"; fi
  [[ -n "\$wfmt" ]] && printf '%s' "\$1"
  exit 0
}
if [[ "\$method" == "PUT" && "\$url" == *api.github.com/repos/*/contents/* ]]; then
  path="\${url##*/contents/}"
  cp "\${data#@}" "$WORKDIR/puts/\${path//\//__}.json"
  emit 200 '{"commit":{"sha":"0123456789abcdef"}}'
fi
case "\$url" in
  *api.github.com/repos/*/contents/data/recordings.json*)
    emit 200 '{"sha":"recsha","content":"$RECS_B64","encoding":"base64"}';;
  *api.github.com/repos/*/contents/links.txt*)
    b64=\$(base64 -w0 < "$LINKS_FIXTURE")
    emit 200 "{\"sha\":\"linksha\",\"content\":\"\$b64\",\"encoding\":\"base64\"}";;
  *api.gofile.io/contents/DeadA1*)  emit 200 '{"status":"error-notFound"}';;
  *api.gofile.io/contents/*)        emit 200 '{"status":"ok"}';;
  *pixeldrain.com/api/file/*/info*) emit 200 '{"success":true,"size":10485760}';;
  *api.github.com*)                 emit 200 '{}';;
  *)                                emit 200 '';;
esac
STUB
chmod +x "$STUBBIN/curl"

run_refresh() {
  rm -f "$WORKDIR"/puts/*
  PATH="$STUBBIN:$PATH" \
  GITHUB_REPOSITORY="fixture/repo" \
  GH_PAT="test-token-not-real" \
  GITHUB_ENV="$WORKDIR/gh-env" \
  REFRESH_PROVIDERS="gofile" \
  DRY_RUN=false \
  bash "$TARGET" >"$WORKDIR/stdout.log" 2>"$WORKDIR/stderr.log"
  return $?
}
put_content() {  # decode the captured PUT for $1 (path with / → __)
  jq -r '.content' "$WORKDIR/puts/$1.json" 2>/dev/null | base64 -d 2>/dev/null
}

echo "── 1: one dead gofile link → links.txt keeps its text format and all entries ──"
make_links_txt "" > "$LINKS_FIXTURE"
RC=0; run_refresh || RC=$?
[[ "$RC" -eq 0 ]] && ok "exit 0" || bad "exit $RC"
grep -q "LINK REFRESH COMPLETE" "$WORKDIR/stdout.log" && ok "reached completion banner" || bad "never completed"
[[ -f "$WORKDIR/puts/links.txt.json" ]] && ok "links.txt was written" || bad "links.txt was NOT written (dead link not marked)"
[[ -f "$WORKDIR/puts/data__recordings.json.json" ]] && bad "recordings.json was written by the refresh (must never be)" || ok "recordings.json untouched"
if [[ -f "$WORKDIR/puts/links.txt.json" ]]; then
  NEW=$(put_content links.txt)
  head -1 <<<"$NEW" | grep -q '^# Stream Recorder links archive' && ok "header preserved" || bad "header lost — first line: $(head -1 <<<"$NEW" | cut -c1-60)"
  jq -e . <<<"$NEW" >/dev/null 2>&1 && bad "links.txt is now JSON (recordings.json copy) — legacy feed overwritten" || ok "not JSON"
  N=$(grep -c '^Title:' <<<"$NEW"); [[ "$N" -eq 3 ]] && ok "all 3 entries kept (incl. the one only links.txt knows)" || bad "entries kept: $N (expected 3)"
  grep -qF "[gofile:HD] ${DEAD_URL} [EXPIRED]" <<<"$NEW" && ok "dead URL marked [EXPIRED] on its own line" || bad "dead URL not marked"
  grep -qF "[gofile:HD] ${LIVE_URL}" <<<"$NEW" && ! grep -qF "${LIVE_URL} [EXPIRED]" <<<"$NEW" && ok "live URL left alone" || bad "live URL marked or lost"
  M=$(grep -o '\[EXPIRED\]' <<<"$NEW" | wc -l); [[ "$M" -eq 1 ]] && ok "exactly one marker written" || bad "$M markers written"
fi

echo "── 2: idempotent — already-marked file is not rewritten (no commit churn) ──"
make_links_txt " [EXPIRED]" > "$LINKS_FIXTURE"
RC=0; run_refresh || RC=$?
[[ "$RC" -eq 0 ]] && ok "exit 0" || bad "exit $RC"
if [[ -f "$WORKDIR/puts/links.txt.json" ]]; then
  NEW=$(put_content links.txt)
  grep -qF "[EXPIRED] [EXPIRED]" <<<"$NEW" && bad "marker doubled: '[EXPIRED] [EXPIRED]'" || true
  bad "links.txt rewritten although nothing changed"
else
  ok "no write when the marker is already present"
fi

echo "── 3: links.txt unreadable → refresh still completes, writes nothing to it ──"
rm -f "$LINKS_FIXTURE"; : > "$LINKS_FIXTURE"   # empty content → read fails
RC=0; run_refresh || RC=$?
[[ "$RC" -eq 0 ]] && ok "exit 0" || bad "exit $RC"
[[ -f "$WORKDIR/puts/links.txt.json" ]] && bad "wrote links.txt from nothing" || ok "no links.txt write"
[[ -f "$WORKDIR/puts/data__recordings.json.json" ]] && bad "recordings.json written" || ok "recordings.json untouched"

echo ""
if (( FAILURES > 0 )); then echo "RESULT: RED — $FAILURES assertion(s) failed"; exit 1; fi
echo "RESULT: GREEN — [EXPIRED] markers land in links.txt, the legacy feed is never overwritten"; exit 0
